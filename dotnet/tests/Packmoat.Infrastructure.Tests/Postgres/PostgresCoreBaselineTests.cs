using Npgsql;

namespace Packmoat.Infrastructure.Tests.Postgres;

/// <summary>
/// The core's PostgreSQL baseline through <see cref="ISchemaMigrator"/>, as the server's start would run it: version 23
/// makes SQLite's final schema (compared fact by fact, <see cref="SchemaShape"/>; the triggers' behaviour is SchemaRulesContract's), plus
/// the truncate guards (<see cref="SchemaShape.PostgresOnlyTriggers"/>), 1 to 22 are empty, and a database recorded part way
/// there is refused. Each test has its own database.
/// </summary>
[Collection(PostgresCollection.Name)]
[Trait("Category", PostgresTestServer.Category)]
public sealed class PostgresCoreBaselineTests : IAsyncLifetime
{
    private PostgresScratchDatabase scratch = null!;

    public async Task InitializeAsync() => scratch = await PostgresScratchDatabase.CreateAsync();

    public async Task DisposeAsync()
    {
        if (scratch is not null) await scratch.DisposeAsync();
    }

    private async Task<IReadOnlyList<TrackOutcome>> MigrateAsync()
    {
        await using var db = scratch.Database();
        return await ((ISchemaMigrator)db).MigrateAsync([]);
    }

    // mutations: a time column as text; GENERATED BY DEFAULT for an identity; an index left out; a CHECK or a foreign key left out;
    // columns in another order; a default dropped; a trigger dropped, made AFTER, on another event or for each statement, or
    // disabled (ALTER TABLE … DISABLE TRIGGER); a truncate guard dropped
    [PostgresFact]
    public async Task The_baseline_is_sqlites_final_schema_plus_the_truncate_guards()
    {
        var sqlite = await CoreSchemaTests.SqliteShapeAsync();
        await MigrateAsync();
        List<string> postgres;
        await using (var c = await scratch.OpenAsync()) postgres = await SchemaShape.ReadAsync(c);

        static bool IsTrigger(string line) => line.StartsWith("trigger ", StringComparison.Ordinal);
        Assert.Empty(SchemaShape.PostgresOnlyTriggers.Intersect(sqlite));
        // The triggers come last on both sides, by name in ordinal order.
        var expected = sqlite.Where(l => !IsTrigger(l))
            .Concat(sqlite.Where(IsTrigger).Concat(SchemaShape.PostgresOnlyTriggers).OrderBy(SchemaShape.TriggerName, StringComparer.Ordinal))
            .ToList();
        var missing = expected.Except(postgres).ToList();
        var extra = postgres.Except(expected).ToList();
        Assert.True(missing.Count == 0 && extra.Count == 0,
            $"PostgreSQL's baseline differs from SQLite's schema.\nOnly in SQLite:\n  {string.Join("\n  ", missing)}\nOnly in PostgreSQL:\n  {string.Join("\n  ", extra)}");
        Assert.Equal(expected, postgres);   // and in the same order: columns in SQLite's order
    }

    private const string Columns =
        """
        FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_class c ON c.oid = a.attrelid JOIN pg_catalog.pg_collation l ON l.oid = a.attcollation
        WHERE c.relnamespace = (SELECT oid FROM pg_catalog.pg_namespace WHERE nspname = current_schema()) AND c.relkind = 'r'
          AND a.attnum > 0 AND NOT a.attisdropped AND c.relname NOT LIKE '%schema\_migrations'
        """;

    /// <summary>Each core column with a collation that is not the built-in "C" (compared by oid), as "table.column collation".</summary>
    private Task<List<string>> NotBuiltInCAsync() =>
        scratch.TextsAsync($"SELECT c.relname || '.' || a.attname || ' ' || {SchemaShape.CollationName} {Columns} AND a.attcollation <> {SchemaShape.BuiltInC}");

    // A collation named "C" in another schema (here an ICU one, which does not order by bytes) is not byte order, and both
    // checks see it: this one and the schema comparison's.
    // mutation (F5): either check compares the collation's name with 'C' again
    [PostgresFact]
    public async Task A_collation_named_C_that_is_not_the_built_in_one_is_seen()
    {
        await MigrateAsync();
        await scratch.ExecuteAsync("CREATE COLLATION public.\"C\" (provider = icu, locale = 'und')");
        await scratch.ExecuteAsync("ALTER TABLE tenants ALTER COLUMN name TYPE text COLLATE public.\"C\"");

        Assert.Equal(["tenants.name public.C"], await NotBuiltInCAsync());
        List<string> shape;
        await using (var c = await scratch.OpenAsync()) shape = await SchemaShape.ReadAsync(c);
        Assert.Contains("tenants collations=[public.C]", shape);
        Assert.Contains("internal_prefixes collations=[]", shape);
    }

    // mutation: COLLATE "C" dropped from one text column (the comparison above reads it as "collations=[default]" too)
    [PostgresFact]
    public async Task Every_text_column_compares_sorts_and_lowers_by_bytes_as_sqlite_does()
    {
        await MigrateAsync();
        Assert.Empty(await NotBuiltInCAsync());
        Assert.Equal(["text 104"], await scratch.TextsAsync($"SELECT pg_catalog.format_type(a.atttypid, NULL) || ' ' || COUNT(*) {Columns} GROUP BY pg_catalog.format_type(a.atttypid, NULL)"));   // 95 at the baseline, + rate_counters.scope and .subject (migration 24), + form_nonces.scope, .nonce_hash and .subject (25), + feed_setup_scratch.tenant_id, .person_oid, .kind and .payload (26)

        // Byte order, as SQLite's BINARY: upper case before lower, and a multi-byte letter after both; lower() changes ASCII letters only.
        foreach (var (id, name) in new[] { ("t1", "ann"), ("t2", "Émile"), ("t3", "Zed") })
            await scratch.ExecuteAsync("INSERT INTO tenants(id, name, upstream_base, allowed_path_prefix, feed_index_url, cooldown_days, created_at) " +
                $"VALUES('{id}', '{name}', 'u', 'p', 'f', 14, '2026-01-01T00:00:00+00:00')");
        Assert.Equal(["Zed", "ann", "Émile"], await scratch.TextsAsync("SELECT name FROM tenants ORDER BY name"));
        Assert.Equal(["Émile"], await scratch.TextsAsync("SELECT lower(name) FROM tenants WHERE lower(name) = 'Émile'"));
        Assert.Equal(["ann"], await scratch.TextsAsync("SELECT name FROM tenants WHERE name < 'a~' AND name > 'Zz'"));
        Assert.Empty(await scratch.TextsAsync("SELECT name FROM tenants WHERE name = 'ANN'"));
    }

    [PostgresFact]   // mutation: the public methods back on a test track, or refusing again
    public async Task Through_the_interface_the_core_runs_to_26_once_and_is_then_current()
    {
        Assert.Equal([new TrackOutcome("core", null, 26, false)], await MigrateAsync());
        var after = await scratch.SnapshotAsync();
        Assert.Equal([new TrackOutcome("core", 26, 26, false)], await MigrateAsync());

        Assert.Equal(after, await scratch.SnapshotAsync());
        Assert.Equal(Enumerable.Range(1, 26), await scratch.VersionsAsync("schema_migrations"));
        await using var db = scratch.Database();
        Assert.Equal([new TrackVersion("core", 26, 26, 26)], await ((ISchemaMigrator)db).TrackVersionsAsync([]));
    }

    [PostgresFact]
    public async Task Track_versions_on_an_empty_database_creates_nothing()
    {
        await using var db = scratch.Database();
        Assert.Equal([new TrackVersion("core", 26, null, 0)], await ((ISchemaMigrator)db).TrackVersionsAsync([]));
        Assert.Empty(await scratch.SnapshotAsync());
    }

    // mutation: the part-way check dropped (version 23 would then run over the database), or only version 22 refused
    [PostgresTheory]
    [InlineData(1)]
    [InlineData(12)]
    [InlineData(22)]
    public async Task A_database_recorded_at_core_version_1_to_22_is_refused_and_nothing_is_written(int version)
    {
        await scratch.ExecuteAsync(
            "CREATE TABLE schema_migrations(version integer PRIMARY KEY, applied_at timestamptz NOT NULL)",
            $"INSERT INTO schema_migrations SELECT v, now() FROM generate_series(1, {version}) AS v");
        var before = await scratch.SnapshotAsync();

        var e = await Assert.ThrowsAsync<SchemaBaselineException>(MigrateAsync);

        Assert.Equal($"The core track is recorded at version {version}, but on PostgreSQL it starts at version 23: versions 1 to 22 are empty there, " +
            "so no Packmoat build made this database. Refusing to run. Nothing was written.", e.Message);
        Assert.Equal(before, await scratch.SnapshotAsync());
    }

    [PostgresFact]   // an empty version table is no version: the track runs from 1
    public async Task An_empty_core_version_table_runs_the_baseline()
    {
        await scratch.ExecuteAsync("CREATE TABLE schema_migrations(version integer PRIMARY KEY, applied_at timestamptz NOT NULL)");
        Assert.Equal([new TrackOutcome("core", 0, 26, false)], await MigrateAsync());
    }

    // NuGet gives an unlisted package's version the published date 1900-01-01: a decision record keeps it exactly.
    [PostgresFact]
    public async Task A_decision_record_published_on_1900_01_01_keeps_its_date()
    {
        await MigrateAsync();
        await scratch.ExecuteAsync(
            """
            INSERT INTO decision_records(tenant_id, ecosystem, package_id, version, decision, reason, published_at, policy_revision, first_seen_at, last_seen_at, seen_count)
            VALUES('acme', 'nuget', 'Old.Package', '1.0.0', 'allowed', 'old-enough', '1900-01-01T00:00:00+00:00', 1, '2026-10-10T12:00:00+00:00', '2026-10-10T12:00:00+00:00', 1)
            """);

        await using var c = await scratch.OpenAsync();
        await using var cmd = new NpgsqlCommand("SELECT published_at, to_char(published_at AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.US') FROM decision_records", c);
        await using var r = await cmd.ExecuteReaderAsync();
        Assert.True(await r.ReadAsync());
        Assert.Equal(new DateTime(1900, 1, 1, 0, 0, 0, DateTimeKind.Utc), r.GetDateTime(0));
        Assert.Equal(DateTimeKind.Utc, r.GetDateTime(0).Kind);
        Assert.Equal("1900-01-01T00:00:00.000000", r.GetString(1));
    }

    // A schema whose name holds a double quote. mutation: Qualified without the "" escape (the name then ends early)
    [PostgresFact]
    public async Task A_schema_named_with_a_double_quote_is_the_one_used()
    {
        await scratch.ExecuteAsync("CREATE SCHEMA \"we\"\"ird\"");
        await scratch.SetSearchPathAsync("\"we\"\"ird\"");

        Assert.Equal([new TrackOutcome("core", null, 26, false)], await MigrateAsync());
        Assert.Equal([new TrackOutcome("core", 26, 26, false)], await MigrateAsync());
        Assert.Equal(Enumerable.Range(1, 26), await scratch.VersionsAsync("\"we\"\"ird\".schema_migrations"));
        Assert.Equal(["we\"ird"], await scratch.TextsAsync("SELECT table_schema::text FROM information_schema.tables WHERE table_name = 'tenants'"));
    }
}
